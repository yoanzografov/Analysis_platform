/**
 * Intelligent Fallback Generator for Undervalued Stocks Ranking (Buffett & Munger Margin of Safety)
 */
export function generateLocalUndervaluedStocks(stocks: Stock[]): string {
  if (!stocks || stocks.length === 0) {
    return `### 🎯 Най-подценени акции в таблицата
В момента списъкът с акции е празен. Заредете основните акции от таблицата или добавете нови, за да изчислим подценяването им спрямо справедливата стойност (Fair Value).`;
  }

  // Filter stocks with valid price and fair price
  const validStocks = stocks
    .filter(s => s.currentPrice > 0 && s.fairPrice > 0)
    .map(s => {
      const discountPct = ((s.fairPrice - s.currentPrice) / s.currentPrice) * 100;
      return { ...s, discountPct };
    })
    .sort((a, b) => b.discountPct - a.discountPct);

  const undervalued = validStocks.filter(s => s.discountPct > 0).slice(0, 5);

  if (undervalued.length === 0) {
    return `### 🎯 Анализ на надцененост / подцененост
Към момента повечето акции в таблицата се търгуват близо или над тяхната консервативна справедлива стойност. 

> [!NOTE]
> Чарли Мънгър винаги е казвал: *"Страхотен бизнес на справедлива цена е по-добър от посредствен бизнес на ниска цена."* Ако няма дълбоко подценени акции с 20%+ марж на сигурност, разумният ход е търпение и задържане на кеш буфер.`;
  }

  let tableRows = undervalued.map((s, idx) => {
    const pE = s.peRatio ? s.peRatio.toFixed(1) : 'N/A';
    const div = s.dividendYield ? `${s.dividendYield.toFixed(2)}%` : (s.dividend || '-');
    return `| **#${idx + 1} ${s.ticker}** | ${s.companyName} | $${s.currentPrice.toFixed(2)} | $${s.fairPrice.toFixed(2)} | **+${s.discountPct.toFixed(1)}%** | ${pE} | ${div} |`;
  }).join('\n');

  return `### 🎯 Топ подценени компании според маржа на сигурност (Margin of Safety)
*Анализ на база текущата пазарна цена спрямо консервативната справедлива стойност:*

| Тикер | Компания | Текуща цена | Справедлива стойност | Марж на сигурност (Потенциал) | P/E Ratio | Дивидент |
| :--- | :--- | :---: | :---: | :---: | :---: | :---: |
${tableRows}

---

### 💡 Коментар и препоръки на стойностния инвеститор:
1. **${undervalued[0].ticker} (${undervalued[0].companyName})**:
   - Води класацията с **+${undervalued[0].discountPct.toFixed(1)}%** потенциал спрямо консервативния модел.
   - Проверете дали спадът в цената се дължи на краткосрочни временни новини (възможност за Бъфет) или на трайно влошаване на конкурентния ров (moat).
2. **Диверсификация**: Не концентрирайте целия си свободен капитал в една подценена позиция. Подходете с поетапно осредняване на позициите (DCA).
3. **Проверка на баланса**: Преди покупка отворете отчета Form 10-K/10-Q и се уверете, че компанията няма прекомерен дълг, падежиращ в условия на по-високи лихви.`;
}

